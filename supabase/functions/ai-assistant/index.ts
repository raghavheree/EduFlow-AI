// Supabase Edge Function: ai-assistant
// Secure Server-Side Google Gemini API Proxy for EduFlow AI
// Follows Deno runtime standards for Supabase Edge Functions.

import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
};

const GEMINI_ENDPOINT = "https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent";

serve(async (req: Request) => {
  // 1. Handle CORS Preflight Requests
  if (req.method === "OPTIONS") {
    return new Response("ok", { headers: corsHeaders });
  }

  if (req.method !== "POST") {
    return new Response(JSON.stringify({ error: "Method not allowed. POST required." }), {
      status: 405,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }

  try {
    // 2. Retrieve Gemini API Key securely from server-side environment secrets
    const geminiApiKey = Deno.env.get("GEMINI_API_KEY");
    if (!geminiApiKey || geminiApiKey.trim().length === 0) {
      return new Response(
        JSON.stringify({
          error: "GEMINI_API_KEY is not configured in server secrets.",
          isConfigured: false,
        }),
        {
          status: 503,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        }
      );
    }

    // 3. Parse and Validate Request Payload
    const body = await req.json().catch(() => null);
    if (!body || typeof body !== "object") {
      return new Response(
        JSON.stringify({ error: "Invalid JSON request body." }),
        {
          status: 400,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        }
      );
    }

    const { action, payload } = body;
    if (!action || !payload) {
      return new Response(
        JSON.stringify({ error: "Missing required 'action' or 'payload' parameters." }),
        {
          status: 400,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        }
      );
    }

    // 4. Dispatch based on Action
    switch (action) {
      case "analyze-notice": {
        const { text, fileName } = payload;
        if (!text || typeof text !== "string") {
          return new Response(JSON.stringify({ error: "Missing or invalid notice text." }), {
            status: 400,
            headers: { ...corsHeaders, "Content-Type": "application/json" },
          });
        }

        const prompt = `You are EduFlow AI's academic administrative assistant.
Analyze this college notice/circular text carefully.
Document Name: ${fileName || "Uploaded notice"}
Content:
"""
${text.slice(0, 30000)}
"""

Return a valid, strict JSON object (no markdown fences, just JSON) with this exact schema:
{
  "title": "Concise official notice title",
  "category": "Exam" | "Assignment" | "Event" | "Holiday" | "Registration" | "General",
  "targetDepartmentCode": "CSE" | "ECE" | "MECH" | "CIVIL" | "MGMT" | "ALL",
  "targetDepartmentName": "Full department name or College-Wide",
  "targetYear": number or null (e.g. 1, 2, 3, 4),
  "targetSemester": number or null (e.g. 1-8),
  "extractedDates": [
    {"label": "Deadline / Date Description", "date": "YYYY-MM-DD or readable date string"}
  ],
  "actionItems": ["Action 1 required from student", "Action 2"],
  "summary": "Clear, professional 2-3 sentence executive summary",
  "confidence": 0.95
}`;

        const geminiRes = await fetch(`${GEMINI_ENDPOINT}?key=${geminiApiKey}`, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            contents: [{ parts: [{ text: prompt }] }],
            generationConfig: { responseMimeType: "application/json", temperature: 0.2 },
          }),
        });

        if (!geminiRes.ok) {
          const errText = await geminiRes.text();
          console.error("[ai-assistant] Gemini API call failed with status:", geminiRes.status);
          return new Response(
            JSON.stringify({ error: "Upstream AI provider error.", status: geminiRes.status }),
            { status: 502, headers: { ...corsHeaders, "Content-Type": "application/json" } }
          );
        }

        const geminiData = await geminiRes.json();
        const candidate = geminiData.candidates?.[0]?.content?.parts?.[0]?.text;
        if (!candidate) {
          return new Response(JSON.stringify({ error: "No response text generated by AI." }), {
            status: 500,
            headers: { ...corsHeaders, "Content-Type": "application/json" },
          });
        }

        const parsed = JSON.parse(candidate);
        return new Response(
          JSON.stringify({
            ...parsed,
            engineUsed: "Gemini 1.5 Flash (Secure Server-Side Supabase Edge Function)",
          }),
          { status: 200, headers: { ...corsHeaders, "Content-Type": "application/json" } }
        );
      }

      case "decompose-assignment": {
        const { title, description } = payload;
        if (!title || !description) {
          return new Response(JSON.stringify({ error: "Missing assignment title or description." }), {
            status: 400,
            headers: { ...corsHeaders, "Content-Type": "application/json" },
          });
        }

        const prompt = `Break down this academic assignment into 3 to 4 sequential, actionable subtasks for a university student.
Title: ${title}
Description: ${description.slice(0, 15000)}

Return a strict JSON array of objects:
[
  { "step": 1, "task": "Subtask title & instruction", "estimated_time": "2 hours" }
]`;

        const geminiRes = await fetch(`${GEMINI_ENDPOINT}?key=${geminiApiKey}`, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            contents: [{ parts: [{ text: prompt }] }],
            generationConfig: { responseMimeType: "application/json" },
          }),
        });

        if (!geminiRes.ok) {
          return new Response(JSON.stringify({ error: "Upstream AI provider error." }), {
            status: 502,
            headers: { ...corsHeaders, "Content-Type": "application/json" },
          });
        }

        const geminiData = await geminiRes.json();
        const candidate = geminiData.candidates?.[0]?.content?.parts?.[0]?.text;
        const parsed = JSON.parse(candidate);

        return new Response(JSON.stringify({ tasks: parsed }), {
          status: 200,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }

      case "study-rag": {
        const { question, bestMatch } = payload;
        if (!question || !bestMatch) {
          return new Response(JSON.stringify({ error: "Missing question or source snippet." }), {
            status: 400,
            headers: { ...corsHeaders, "Content-Type": "application/json" },
          });
        }

        const prompt = `You are EduFlow AI's academic study assistant. Answer the student's question using ONLY the retrieved lecture notes snippet below.
Question: "${question}"
Source Document: "${bestMatch.docTitle}" (Unit ${bestMatch.unit}, Page ${bestMatch.page})
Text Snippet:
"""
${bestMatch.text}
"""

Provide a clear, pedagogical explanation with bullet points and a concrete example where appropriate. Conclude with an explicit citation: [Source: ${bestMatch.docTitle}, Page ${bestMatch.page}].`;

        const geminiRes = await fetch(`${GEMINI_ENDPOINT}?key=${geminiApiKey}`, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ contents: [{ parts: [{ text: prompt }] }] }),
        });

        if (!geminiRes.ok) {
          return new Response(JSON.stringify({ error: "Upstream AI provider error." }), {
            status: 502,
            headers: { ...corsHeaders, "Content-Type": "application/json" },
          });
        }

        const geminiData = await geminiRes.json();
        const text = geminiData.candidates?.[0]?.content?.parts?.[0]?.text;

        return new Response(JSON.stringify({ answer: text }), {
          status: 200,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }

      case "analyze-exam-syllabus": {
        const { subjectName, syllabusText, daysUntilExam, availableHours, dailyHours } = payload;

        const prompt = `Analyze this college syllabus for the subject "${subjectName}".
The student has an exam in ${daysUntilExam} days and has ${availableHours} total study hours available (~${dailyHours} hrs/day).
Syllabus:
"""
${(syllabusText || "").slice(0, 20000)}
"""

Return a strict JSON object with:
{
  "priority_topics": [
    {
      "name": "Topic Name",
      "priority": "high" | "medium" | "low",
      "weightage_pct": number (e.g. 35),
      "suggested_hours": number,
      "justification": "Why this topic is prioritized based on foundational depth and exam patterns",
      "important_subtopics": ["Subtopic 1", "Subtopic 2"],
      "study_order": 1
    }
  ],
  "study_phases": [
    { "phase_name": "Phase 1: Foundations", "duration": "Days 1-4", "focus": "Master high-yield core concepts" }
  ],
  "revision_checklist": [
    { "item": "Revise high-priority theorems and proofs", "checked": false }
  ]
}`;

        const geminiRes = await fetch(`${GEMINI_ENDPOINT}?key=${geminiApiKey}`, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            contents: [{ parts: [{ text: prompt }] }],
            generationConfig: { responseMimeType: "application/json" },
          }),
        });

        if (!geminiRes.ok) {
          return new Response(JSON.stringify({ error: "Upstream AI provider error." }), {
            status: 502,
            headers: { ...corsHeaders, "Content-Type": "application/json" },
          });
        }

        const geminiData = await geminiRes.json();
        const candidate = geminiData.candidates?.[0]?.content?.parts?.[0]?.text;
        const parsed = JSON.parse(candidate);

        return new Response(JSON.stringify(parsed), {
          status: 200,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }

      default:
        return new Response(JSON.stringify({ error: `Unsupported action: ${action}` }), {
          status: 400,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
    }
  } catch (err: any) {
    // Sanitized error logging that never outputs credentials or keys
    console.error("[ai-assistant] Internal server error processing request:", err?.message || "Unknown");
    return new Response(JSON.stringify({ error: "Internal server error occurred." }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
